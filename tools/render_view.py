# Design: docs/design/figma-to-code.md
"""Host renderer: vẽ một view (.gen.c) trên PC bằng ink_ui thật, ghi ra ảnh để so với Figma.

    python tools/render_view.py <view> [--data data.json] [--part <tên>] [--scale N] [-o out.png]

<view> là tên view (ví dụ example_view) hoặc đường dẫn tới file .gen.h.
Dữ liệu mặc định: <view>.sample.json cạnh file .gen.h. Đuôi -o chọn định dạng: .png hoặc .pbm.
Cần gcc, cmake, ninja trong PATH (terminal ESP-IDF). Build trong build-render/.
"""
import argparse
import glob
import json
import os
import re
import shutil
import struct
import subprocess
import sys
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUILD_DIR = os.path.join(ROOT, "build-render")
NINJA_FALLBACK = r"C:\Espressif\tools\ninja\1.12.1"

# Panel frame K1: 1 bit per pixel, bit 1 = white, MSB = leftmost pixel, rows packed with no padding.
# A landscape view (416 x 240) is drawn on a canvas rotated by INK_UI_ROTATION_90; the image is turned back to the Figma
# orientation, so the result looks the same for any landscape rotation the app picks.
PANEL_WIDTH = 240
PANEL_HEIGHT = 416
FRAME_BYTES = PANEL_WIDTH // 8 * PANEL_HEIGHT

VIEW_DIRS = ("components/apps/*/views", "templates/components/*/views")
IDENT_RE = re.compile(r"[A-Za-z_]\w*")

MAIN_TEMPLATE = """/* Generated by tools/render_view.py; do not edit. */
#include "{view}.gen.h"
#include "ink_ui.h"
#include <stdio.h>
#include <string.h>

static const {view}_data_t s_data = {init};

int main(int argc, char **argv) {{
    if (argc != 2) {{ return 2; }}
    static uint8_t                 frame[{frame_bytes}];
    const ink_display_frame_info_t info = {{.width = {width}, .height = {height}, .format = INK_DISPLAY_PIXEL_FORMAT_K1}};
    ink_ui_canvas_t                canvas;
    if (ink_ui_canvas_init(&canvas, &info, {rotation}) != INK_UI_OK) {{ return 1; }}
    memset(frame, 0xFF, sizeof(frame)); /* white */
    ink_ui_canvas_bind(&canvas, frame);
    {draw}(&canvas, &s_data);
    FILE *fp = fopen(argv[1], "wb");
    if (fp == nullptr) {{ return 1; }}
    const size_t written = fwrite(frame, 1, sizeof(frame), fp);
    fclose(fp);
    return written == sizeof(frame) ? 0 : 1;
}}
"""


def rel(path):
    """Path relative to the repo when inside it, absolute otherwise (another drive on Windows)."""
    path = os.path.abspath(path)
    try:
        inside = os.path.commonpath([path, ROOT]) == ROOT
    except ValueError:
        inside = False
    return os.path.relpath(path, ROOT) if inside else path


def fail(msg):
    print(f"Lỗi: {msg}", file=sys.stderr)
    sys.exit(1)


def find_view(arg):
    """Return (view name, path of .gen.h) from a view name or a .gen.h path."""
    if arg.endswith(".gen.h"):
        if not os.path.isfile(arg):
            fail(f"không có file {arg}")
        return os.path.basename(arg)[: -len(".gen.h")], os.path.abspath(arg)
    found = []
    for pattern in VIEW_DIRS:
        found += glob.glob(os.path.join(ROOT, pattern, f"{arg}.gen.h"))
    if not found:
        fail(f"không thấy {arg}.gen.h trong {', '.join(VIEW_DIRS)}")
    if len(found) > 1:
        fail("nhiều view trùng tên, truyền đường dẫn .gen.h:\n  " + "\n  ".join(rel(p) for p in found))
    return arg, found[0]


def c_string(text):
    """C string literal; UTF-8 kept as is, quotes, backslash and control characters escaped."""
    out = []
    for ch in text:
        if ch in '"\\':
            out.append("\\" + ch)
        elif ch == "\n":
            out.append("\\n")
        elif ord(ch) < 0x20:
            out.append(f"\\{ord(ch):03o}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def c_value(value, where):
    """C initializer for one JSON value. A list also gets `<key>_count` in its parent (see c_struct)."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return "nullptr"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return c_string(value)
    if isinstance(value, dict):
        return c_struct(value, where)
    if isinstance(value, list):
        return "{" + ", ".join(c_value(v, f"{where}[{i}]") for i, v in enumerate(value)) + "}"
    fail(f"{where}: kiểu JSON không hỗ trợ")


def c_struct(obj, where):
    """Designated initializer for a JSON object; a list field `x` adds `.x_count` unless the JSON gives it."""
    fields = []
    for key, value in obj.items():
        if not IDENT_RE.fullmatch(key):
            fail(f"{where}: '{key}' không phải tên field C")
        fields.append(f".{key} = {c_value(value, f'{where}.{key}')}")
        if isinstance(value, list) and f"{key}_count" not in obj:
            fields.append(f".{key}_count = {len(value)}")
    return "{" + ", ".join(fields) + "}"


def view_parts(view, header_text):
    return re.findall(rf"\bvoid\s+{view}_draw_(\w+)\s*\(", header_text)


def view_size(view, header_text):
    """(width, height) of the view canvas from <VIEW>_WIDTH / <VIEW>_HEIGHT; portrait when the header has none."""
    w = re.search(rf"#define\s+{view.upper()}_WIDTH\s+(\d+)", header_text)
    h = re.search(rf"#define\s+{view.upper()}_HEIGHT\s+(\d+)", header_text)
    size = (int(w.group(1)), int(h.group(1))) if w and h else (PANEL_WIDTH, PANEL_HEIGHT)
    if size not in ((PANEL_WIDTH, PANEL_HEIGHT), (PANEL_HEIGHT, PANEL_WIDTH)):
        fail(f"view {view} cỡ {size[0]} x {size[1]}: chỉ nhận {PANEL_WIDTH} x {PANEL_HEIGHT} hoặc {PANEL_HEIGHT} x {PANEL_WIDTH}")
    return size


def frame_pixel(frame, x, y):
    return (frame[y * PANEL_WIDTH // 8 + x // 8] >> (7 - x % 8)) & 1


def write_image(frame, path, scale, landscape):
    """Write the K1 frame as PNG (1 bit gray, 1 = white like K1) or PBM P4 (1 = black), in the view orientation."""
    if landscape:
        # INK_UI_ROTATION_90 (clockwise): view pixel (x, y) is panel pixel (PANEL_WIDTH - 1 - y, x).
        src_w, src_h = PANEL_HEIGHT, PANEL_WIDTH
        pixel = lambda x, y: frame_pixel(frame, PANEL_WIDTH - 1 - y, x)  # noqa: E731
    else:
        src_w, src_h = PANEL_WIDTH, PANEL_HEIGHT
        pixel = lambda x, y: frame_pixel(frame, x, y)  # noqa: E731
    width, height = src_w * scale, src_h * scale
    rows = []
    for y in range(src_h):
        bits = [pixel(x, y) for x in range(src_w) for _ in range(scale)]
        packed = bytes(sum(bits[i + b] << (7 - b) for b in range(8)) for i in range(0, width, 8))
        rows += [packed] * scale
    if path.lower().endswith(".pbm"):
        with open(path, "wb") as f:
            f.write(f"P4\n{width} {height}\n".encode())
            for row in rows:
                f.write(bytes(~b & 0xFF for b in row))
        return

    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    raw = b"".join(b"\x00" + bytes(row) for row in rows)
    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n")
        f.write(chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 1, 0, 0, 0, 0)))
        f.write(chunk(b"IDAT", zlib.compress(raw, 9)))
        f.write(chunk(b"IEND", b""))


def run(cmd, env, what):
    result = subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True, encoding="utf-8", errors="replace")
    if result.returncode != 0:
        print(result.stdout + result.stderr, file=sys.stderr)
        fail(what)


def compare_png(frame, landscape, figma_png, diff_path):
    """Compare the render with a Figma export (luminance < 128 = black) and print the diff pixel count at shifts -2..2.
    Writes the diff at shift (0, 0) as a PBM (black = differs). Shift (dx, dy): render(x + dx, y + dy) vs figma(x, y)."""
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from figma2ink import png_alpha  # noqa: E402
    with open(figma_png, "rb") as f:
        width, height, luma = png_alpha(f.read(), luma=True)
    if landscape:
        ours = lambda x, y: frame_pixel(frame, PANEL_WIDTH - 1 - y, x)  # noqa: E731
        size = (PANEL_HEIGHT, PANEL_WIDTH)
    else:
        ours = lambda x, y: frame_pixel(frame, x, y)  # noqa: E731
        size = (PANEL_WIDTH, PANEL_HEIGHT)
    if (width, height) != size:
        fail(f"{figma_png} là {width} x {height}, render là {size[0]} x {size[1]}")
    diffs = {}
    for dy in range(-2, 3):
        for dx in range(-2, 3):
            diffs[(dx, dy)] = sum((ours(x + dx, y + dy) == 0) != (luma[y][x] < 128)
                                  for y in range(max(0, -dy), min(height, height - dy))
                                  for x in range(max(0, -dx), min(width, width - dx)))
    best = min(diffs, key=diffs.get)
    print(f"So với {rel(figma_png)}: lệch {diffs[(0, 0)]} pixel ở (0,0); tốt nhất {diffs[best]} pixel ở dịch {best}")
    rows = [bytes(sum(((ours(x + b, y) == 0) != (luma[y][x + b] < 128)) << (7 - b) for b in range(8) if x + b < width)
                  for x in range(0, width, 8)) for y in range(height)]
    with open(diff_path, "wb") as f:
        f.write(f"P4\n{width} {height}\n".encode() + b"".join(rows))


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stderr.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description="Vẽ một view .gen.c trên PC ra ảnh PNG hoặc PBM")
    parser.add_argument("view", help="tên view (example_view) hoặc đường dẫn file .gen.h")
    parser.add_argument("--data", help="file JSON điền struct <view>_data_t; mặc định <view>.sample.json cạnh .gen.h")
    parser.add_argument("--part", help="chỉ vẽ part này (<view>_draw_<part>) lên nền trắng")
    parser.add_argument("--scale", type=int, default=1, help="phóng mỗi pixel thành N x N (mặc định 1)")
    parser.add_argument("--compare", help="PNG xuất từ Figma: in số pixel lệch và ghi <output>_diff.pbm")
    parser.add_argument("-o", "--output", help="file ảnh .png hoặc .pbm; mặc định build-render/<view>[_<part>].png")
    args = parser.parse_args()

    view, header = find_view(args.view)
    source = header[: -len(".h")] + ".c"
    if not os.path.isfile(source):
        fail(f"không có {rel(source)}")
    header_text = open(header, encoding="utf-8").read()
    parts = view_parts(view, header_text)
    size = view_size(view, header_text)
    landscape = size[0] > size[1]
    draw = f"{view}_draw"
    if args.part:
        if args.part not in parts:
            fail(f"view {view} không có part '{args.part}'; các part: {', '.join(parts) or '(không có)'}")
        draw = f"{view}_draw_{args.part}"
    if args.scale < 1:
        fail("--scale phải >= 1")

    data_path = args.data or header[: -len(".gen.h")] + ".sample.json"
    if not os.path.isfile(data_path):
        fail(f"không có file dữ liệu {data_path}; truyền --data")
    try:
        with open(data_path, encoding="utf-8") as f:
            data = json.load(f)
    except json.JSONDecodeError as e:
        fail(f"{data_path}: JSON lỗi: {e}")
    if not isinstance(data, dict):
        fail(f"{data_path}: phải là một object JSON")

    output = args.output or os.path.join(BUILD_DIR, f"{view}{'_' + args.part if args.part else ''}.png")
    if not output.lower().endswith((".png", ".pbm")):
        fail("đuôi -o phải là .png hoặc .pbm")

    os.makedirs(BUILD_DIR, exist_ok=True)
    main_c = os.path.join(BUILD_DIR, "render_main.c")
    text = MAIN_TEMPLATE.format(view=view, init=c_struct(data, "data"), draw=draw, frame_bytes=FRAME_BYTES,
                                width=PANEL_WIDTH, height=PANEL_HEIGHT,
                                rotation="INK_UI_ROTATION_90" if landscape else "INK_UI_ROTATION_0")
    with open(main_c, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)

    env = dict(os.environ)
    if not shutil.which("ninja", path=env.get("PATH")) and os.path.isdir(NINJA_FALLBACK):
        env["PATH"] = NINJA_FALLBACK + os.pathsep + env.get("PATH", "")
    run(["cmake", "-S", "tools/render_view", "-B", BUILD_DIR, "-G", "Ninja", "-DCMAKE_C_COMPILER=gcc",
         f"-DRENDER_MAIN={main_c.replace(os.sep, '/')}", f"-DVIEW_SOURCE={source.replace(os.sep, '/')}"],
        env, "cấu hình CMake")
    run(["cmake", "--build", BUILD_DIR], env,
        f"build view; field trong {rel(data_path)} phải khớp struct {view}_data_t")

    raw = os.path.join(BUILD_DIR, "frame.k1")
    run([os.path.join(BUILD_DIR, "render_view"), raw], env, "chạy view")
    with open(raw, "rb") as f:
        frame = f.read()
    if len(frame) != FRAME_BYTES:
        fail(f"frame {len(frame)} byte, cần {FRAME_BYTES}")
    os.makedirs(os.path.dirname(os.path.abspath(output)), exist_ok=True)
    write_image(frame, output, args.scale, landscape)
    print(f"Đã vẽ {draw} → {rel(output)} ({size[0] * args.scale} x {size[1] * args.scale})")
    if args.compare:
        compare_png(frame, landscape, args.compare, os.path.splitext(output)[0] + "_diff.pbm")


if __name__ == "__main__":
    main()
