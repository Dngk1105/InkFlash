# Design: docs/design/ui.md
"""Chép một font của U8g2 ra file C riêng cho ink_ui.

U8g2 gom mọi font vào một file third_party/u8g2/csrc/u8g2_fonts.c (39,7 MB) nên firmware không biên dịch file đó.
Script này tìm mảng font theo tên, chép nguyên dữ liệu và bọc trong một biến ink_ui_font_t.

  python tools/u8g2_font.py u8g2_font_unifont_t_vietnamese2 unifont_vi_16
      sinh components/core/ink_ui/fonts/ink_ui_font_unifont_vi_16.c với biến ink_ui_font_unifont_vi_16

Sinh xong thì thêm file vào SRCS của components/core/ink_ui/CMakeLists.txt và khai báo biến trong ink_ui.h.
Giấy phép của từng font: third_party/u8g2/LICENSE.
"""
import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "third_party", "u8g2", "csrc", "u8g2_fonts.c")
OUT_DIR = os.path.join(ROOT, "components", "core", "ink_ui", "fonts")


def find_font(name):
    """Trả (số byte, các dòng chuỗi) của mảng font `name`."""
    head = re.compile(r"^const uint8_t " + re.escape(name) + r"\[(\d+)\]")
    size, lines = None, []
    with open(SOURCE, encoding="latin-1") as f:
        for line in f:
            if size is None:
                m = head.match(line)
                if m:
                    size = int(m.group(1))
                continue
            text = line.strip()
            done = text.endswith(";")
            lines.append(text[:-1] if done else text)
            if done:
                return size, lines
    sys.exit(f"u8g2_font.py: không thấy font '{name}' trong {SOURCE}" if size is None else f"u8g2_font.py: font '{name}' không có dấu ';' kết thúc")


def main():
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")  # console Windows mặc định không in được tiếng Việt
    parser = argparse.ArgumentParser(description="Chép một font của U8g2 ra file C cho ink_ui")
    parser.add_argument("u8g2_name", help="tên mảng font trong u8g2_fonts.c, ví dụ u8g2_font_unifont_t_vietnamese2")
    parser.add_argument("name", help="tên ngắn, chữ thường và gạch dưới; biến sinh ra là ink_ui_font_<name>")
    args = parser.parse_args()
    if not re.fullmatch(r"[a-z][a-z0-9_]*", args.name):
        sys.exit("u8g2_font.py: tên ngắn chỉ gồm chữ thường, số, gạch dưới")
    if not os.path.isfile(SOURCE):
        sys.exit(f"u8g2_font.py: thiếu {SOURCE}; chạy git submodule update --init")

    size, lines = find_font(args.u8g2_name)
    symbol = f"ink_ui_font_{args.name}"
    out = [
        "/* Design: docs/design/ui.md */",
        "",
        f"/* Generated by tools/u8g2_font.py from {args.u8g2_name} (third_party/u8g2/csrc/u8g2_fonts.c). Do not edit.",
        " * Font license: third_party/u8g2/LICENSE. */",
        '#include "ink_ui.h"',
        "",
        "/* clang-format off */",
        f"static const uint8_t data[{size}] =",
    ]
    out += ["    " + line for line in lines[:-1]] + ["    " + lines[-1] + ";", "/* clang-format on */", "", f"const ink_ui_font_t {symbol} = {{.data = data}};", ""]
    os.makedirs(OUT_DIR, exist_ok=True)
    path = os.path.join(OUT_DIR, symbol + ".c")
    with open(path, "w", encoding="latin-1", newline="\n") as f:
        f.write("\n".join(out))
    print(f"Đã sinh {os.path.relpath(path, ROOT)} ({size} byte)")


if __name__ == "__main__":
    main()
