#pragma once

/*
 * Driver for the WeAct 3.7" panel (UC8253 controller, 240 × 416 px), implementing ink_hal_display.
 * The BSP initializes the SPI bus and passes the pins in config. The caller provides the driver struct;
 * WARN: it must be in internal RAM because DMA reads window_buffer.
 */
#include "driver/gpio.h"
#include "driver/spi_master.h"
#include "esp_err.h"
#include "freertos/FreeRTOS.h"
#include "freertos/semphr.h"
#include "ink_hal_display.h"
#include <stdint.h>

#define INK_DRV_UC8253_WIDTH                    240
#define INK_DRV_UC8253_HEIGHT                   416
#define INK_DRV_UC8253_FRAME_BYTES              (INK_DRV_UC8253_WIDTH / 8 * INK_DRV_UC8253_HEIGHT)
#define INK_DRV_UC8253_TABLE_COUNT              5  /* LUTC, LUTWW, LUTKW, LUTWK, LUTKK (commands 0x20-0x24) */
#define INK_DRV_UC8253_TABLE_BYTES              42 /* 6 groups × 7 bytes, KW mode */
#define INK_DRV_UC8253_NAME_BYTES               16
#define INK_DRV_UC8253_MAX_PROFILES             32                /* slots in capabilities, including the temporary profile */
#define INK_DRV_UC8253_OTP_BYTES                (0x2A + 9 * 0xE9) /* bank 0 from key A5 to the end of band TR8 (waveform.md) */
#define INK_DRV_UC8253_PSR_SECOND_DEFAULT       0x0A              /* TIEG 0, NORG 1, VC_LUTZ 0: least darkening after POF (refresh.md) */
#define INK_DRV_UC8253_VCOM_FROM_PROFILE        0xFF              /* keep the profile's VCOM_DC */
#define INK_DRV_UC8253_POWER_OFF_FRAMES_DEFAULT 1                 /* UC8253 PFS default: gate off 1 frame after source */

typedef struct {
    spi_host_device_t host; /**< initialized bus, max_transfer_sz >= INK_DRV_UC8253_FRAME_BYTES */
    gpio_num_t        cs;
    gpio_num_t        dc;
    gpio_num_t        reset;
    gpio_num_t        busy;
    uint32_t          spi_clock_hz; /**< 0 = 4 MHz */
} ink_drv_uc8253_config_t;

/** One waveform profile, loaded through registers (REG = 1). Generated by tools/profile_gen.py. */
typedef struct {
    uint16_t    id;
    const char *name;
    uint8_t     source;   /**< 0–8 = TR0–TR8, INK_HAL_DISPLAY_SOURCE_CUSTOM */
    uint8_t     scans;    /**< DRFs per draw, 1-4 */
    uint8_t     pll;      /**< command 0x30 byte */
    uint8_t     power[4]; /**< VG, VSH, VSL, VDHR: bytes 2-5 of command 0x01 */
    uint8_t     vcom;     /**< command 0x82 byte */
    uint8_t     eopt;
    uint8_t     xon[2];
    uint16_t    drf_ms; /**< one DRF */
    uint8_t     tables[INK_DRV_UC8253_TABLE_COUNT][INK_DRV_UC8253_TABLE_BYTES];
} ink_drv_uc8253_profile_t;

typedef struct {
    ink_drv_uc8253_config_t config;

    /** Display task only. */
    const ink_drv_uc8253_profile_t *temporary_profile; /**< NULL = no temporary profile loaded */
    int                             loaded_profile;    /**< profile loaded in the controller registers; -1 = none */
    bool                            power_on;          /**< analog power on (after PON, before POF) */
    bool                            ram_trusted;       /**< image RAM matches the planes of the previous draw; false after reset */
    bool                            ram_swapped;       /**< odd DRF count since reset: 0x10 is the NEW area */
    bool                            needs_reset;       /**< previous draw failed midway: RAM swap state unknown */
    uint8_t                         psr_second;        /**< PSR byte 2 sent to the controller */
    uint8_t                         power_off_frames;  /**< PFS sent: frames from source off to gate off */
    uint8_t                         vcom_override;     /**< command 0x82 byte replacing the profile's; 0xFF = none */

    /** Requests from other tasks, guarded by request_lock; draw (and power_off for PSR) takes them. */
    portMUX_TYPE             request_lock;
    bool                     temporary_pending;
    ink_drv_uc8253_profile_t temporary_request;
    char                     temporary_request_name[INK_DRV_UC8253_NAME_BYTES];
    ink_drv_uc8253_profile_t temporary;
    char                     temporary_name[INK_DRV_UC8253_NAME_BYTES];
    bool                     psr_second_pending;
    uint8_t                  psr_second_request;
    bool                     power_off_frames_pending;
    uint8_t                  power_off_frames_request;
    bool                     vcom_override_pending;
    uint8_t                  vcom_override_request;

    ink_hal_display_profile_info_t profile_info[INK_DRV_UC8253_MAX_PROFILES];

    spi_device_handle_t spi;
    SemaphoreHandle_t   busy_ready; /**< given by the ISR when BUSY goes high */
    StaticSemaphore_t   busy_ready_storage;
    uint8_t             window_buffer[INK_DRV_UC8253_FRAME_BYTES] __attribute__((aligned(4)));
} ink_drv_uc8253_t;

/**
 * @brief Reset the controller, send the panel config and fill `out_device`. The image on the panel is unchanged.
 *        Capabilities list the built-in profiles, then the temporary profile.
 * @par Called from
 * BSP, once, from a task.
 * @retval ESP_ERR_INVALID_ARG a pointer is NULL.
 * @retval ESP_ERR_TIMEOUT BUSY did not go high.
 * @retval other GPIO or SPI error.
 */
esp_err_t ink_drv_uc8253_init(ink_drv_uc8253_t *driver, const ink_drv_uc8253_config_t *config, ink_hal_display_device_t *out_device);

/**
 * @brief Load a `.inkw` blob (tools/profile_gen.py --blob) as the temporary profile, effective from the next draw.
 *        Bench firmware only.
 * @par Called from
 * A task other than the display task, or the display task between draws.
 * @retval ESP_ERR_INVALID_ARG a pointer is NULL, or magic, version, length or CRC is wrong; the old temporary profile is kept.
 */
esp_err_t ink_drv_uc8253_load_temporary(ink_drv_uc8253_t *driver, const uint8_t *blob, size_t length);

/**
 * @brief Read the first INK_DRV_UC8253_OTP_BYTES bytes of OTP into `out` with command 0xA2. Bench firmware only.
 * @par Called from
 * The task that calls draw; never concurrently with draw.
 * @retval ESP_ERR_INVALID_ARG a pointer is NULL, or length < INK_DRV_UC8253_OTP_BYTES.
 * @retval other SPI error.
 */
esp_err_t ink_drv_uc8253_read_otp(ink_drv_uc8253_t *driver, uint8_t *out, size_t length);

/**
 * @brief Set PSR byte 2 (VCMZ, TS_AUTO, TIEG, NORG, VC_LUTZ; commands.md); sent to the controller before the next draw
 *        or power off. Default INK_DRV_UC8253_PSR_SECOND_DEFAULT. Bench firmware only.
 * @par Called from
 * Any task.
 * @retval ESP_ERR_INVALID_ARG driver is NULL, or `value` has bits D7-D5 set.
 */
esp_err_t ink_drv_uc8253_set_psr_second(ink_drv_uc8253_t *driver, uint8_t value);

/**
 * @brief Get PSR byte 2 set most recently, even if not yet sent to the controller.
 * @par Called from
 * Any task.
 * @return PSR byte 2.
 */
uint8_t ink_drv_uc8253_psr_second(ink_drv_uc8253_t *driver);

/**
 * @brief Replace VCOM_DC (command 0x82 byte) of every profile with `value`, effective from the next draw;
 *        INK_DRV_UC8253_VCOM_FROM_PROFILE restores each profile's own. Bench firmware only.
 * @par Called from
 * Any task.
 * @retval ESP_ERR_INVALID_ARG driver is NULL, or `value` > 0x7E and not INK_DRV_UC8253_VCOM_FROM_PROFILE.
 */
esp_err_t ink_drv_uc8253_set_vcom_override(ink_drv_uc8253_t *driver, uint8_t value);

/**
 * @brief Get the replacement VCOM_DC set most recently, even if not yet sent to the controller.
 * @par Called from
 * Any task.
 * @return VCOM_DC byte, or INK_DRV_UC8253_VCOM_FROM_PROFILE.
 */
uint8_t ink_drv_uc8253_vcom_override(ink_drv_uc8253_t *driver);

/**
 * @brief Set the frames from source off to gate off at POF (PFS command `0x03`); sent to the controller before the
 *        next draw or power off. Default INK_DRV_UC8253_POWER_OFF_FRAMES_DEFAULT. Bench firmware only.
 * @par Called from
 * Any task.
 * @retval ESP_ERR_INVALID_ARG driver is NULL, or `frames` is outside 1-4.
 */
esp_err_t ink_drv_uc8253_set_power_off_frames(ink_drv_uc8253_t *driver, uint8_t frames);

/**
 * @brief Get the PFS frame count set most recently, even if not yet sent to the controller.
 * @par Called from
 * Any task.
 * @return Frames, 1-4.
 */
uint8_t ink_drv_uc8253_power_off_frames(ink_drv_uc8253_t *driver);
